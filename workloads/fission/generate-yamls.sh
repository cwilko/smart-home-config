#!/bin/bash
# Renders the Fission Helm chart into one file per chart template directory (router, executor, timer, ...),
# without Secrets or hook resources, so you can apply only the components you want. Components we don't run by default
# (OPTIONAL below) go in optional/, everything else in install/.
# Assumes the namespaces already exist (apply namespace.yaml first). Applies the sealed secrets in secrets/, waits for
# the sealed-secrets controller to unseal fission-webhook-certs, and reads its ca.crt from the cluster: the webhooks'
# caBundle has to be that CA. Only ca.crt (public) is read from the Secret. Requires: helm, kubectl with access to the
# cluster.
set -euo pipefail

cd "$(dirname "${BASH_SOURCE[0]}")"

CHART_VERSION=1.27.0
NS=automation
SECRET=fission-webhook-certs
# Template directories rendered into optional/ instead of install/: timer (TimeTrigger / cron), kubewatcher
# (KubernetesWatchTrigger), webhook-server (admission webhook; the CRDs validate themselves, so it isn't needed),
# storagesvc (archive storage; code is built outside the cluster and referenced by URL, so it isn't needed), and the
# RBAC-only leftovers of features disabled in helm-values.yaml (mqt-keda, mqt-fission-kafka, fluentbit - the chart renders
# their ServiceAccounts and Roles even though their Deployments are gated off). buildermgr stays in install/: even with
# nothing to build it sets status.buildstatus on every Package, and without that the fetcher refuses the package.
OPTIONAL=" timer kubewatcher webhook-server storagesvc mqt-keda mqt-fission-kafka fluentbit "

WORK=$(mktemp -d)
trap 'rm -rf "$WORK"' EXIT

echo "== Applying sealed secrets =="
kubectl apply -f secrets/

echo "== Waiting for $SECRET to be unsealed =="
OWNER=
for _ in $(seq 1 30); do
  OWNER=$(kubectl get secret "$SECRET" -n "$NS" -o jsonpath='{.metadata.ownerReferences[*].kind}' 2>/dev/null || true)
  [ "$OWNER" = "SealedSecret" ] && break
  sleep 2
done
if [ "$OWNER" != "SealedSecret" ]; then
  echo "$SECRET in $NS was not created by sealed-secrets (owner: '${OWNER:-none}') - is an older Secret with that name in the way?" >&2
  exit 1
fi

kubectl get secret "$SECRET" -n "$NS" -o jsonpath='{.data.ca\.crt}' | base64 -d > "$WORK/ca.crt"
openssl x509 -in "$WORK/ca.crt" -noout -subject

# The chart reuses webhook.crtPEM as the webhooks' caBundle, so it gets the CA cert. webhook.keyPEM only has to be
# non-empty: the chart's own fission-webhook-certs Secret is dropped below in favour of the sealed one.
echo "== Rendering install/ and optional/ =="
helm template fission fission-all --repo https://fission.github.io/fission-charts/ --version "$CHART_VERSION" \
  --namespace "$NS" -f helm-values.yaml \
  --set-file webhook.caBundlePEM="$WORK/ca.crt" --set-file webhook.crtPEM="$WORK/ca.crt" --set webhook.keyPEM=unused \
  > "$WORK/rendered.yaml"

# Drop Secrets and helm hook resources (the pre-upgrade checks), and group the rest by the chart template directory in
# helm's "# Source:" comment. The chart leaves metadata.namespace off Deployments and Services (helm supplies it at
# install time), so add it or kubectl apply would use the current namespace.
mkdir "$WORK/parts"
awk -v out="$WORK/parts" -v ns="$NS" '
function flush() {
  if (doc == "") return
  # helm writes the Source comment once per template file, so a second document from the same file (e.g. the
  # validating webhook config after the mutating one) inherits the previous document'"'"'s directory
  if (match(doc, /# Source: fission-all\/templates\/[^\/\n]+\//)) {
    prefix = length("# Source: fission-all/templates/")
    dir = substr(doc, RSTART + prefix, RLENGTH - prefix - 1)
  }
  if (dir == "") { print "no template directory known for:\n" doc > "/dev/stderr"; exit 1 }
  if (doc !~ /\nkind: Secret\n/ && doc !~ /helm.sh\/hook/) {
    # Prefix control-plane Deployments (and so their pods) with fission-, since they share a namespace with other apps
    if (doc ~ /\nkind: Deployment\n/) sub(/\n  name: /, "\n  name: fission-", doc)
    if (doc ~ /\nkind: (Deployment|Service)\n/ && doc !~ /\n  namespace: /) sub(/\n  name: [^\n]+/, "&\n  namespace: " ns, doc)
    printf "---\n%s", doc >> (out "/" dir ".yaml")
  }
  doc = ""
}
/^---$/ { flush(); next }
{ doc = doc $0 "\n" }
END { flush() }' "$WORK/rendered.yaml"

rm -rf install optional
mkdir install optional
for f in "$WORK"/parts/*.yaml; do
  name=$(basename "$f")
  case "$OPTIONAL" in *" ${name%.yaml} "*) out=optional ;; *) out=install ;; esac
  {
    echo "# Generated by generate-yamls.sh from fission-all $CHART_VERSION (chart template directory: ${name%.yaml}). Do not edit by hand."
    cat "$f"
  } > "$out/$name"
  echo "Wrote $out/$name ($(grep -c '^kind:' "$f") resources)"
done

echo "== Checks =="
EXPECTED=$(printf '%s' "$(cat "$WORK/ca.crt")" | base64 | tr -d '\n')
BUNDLES=$(grep -h 'caBundle:' install/*.yaml optional/*.yaml | awk '{print $2}' | tr -d '"' | sort -u)
[ "$BUNDLES" = "$EXPECTED" ] && echo "webhook caBundle matches the CA in $SECRET" || { echo "caBundle does not match the CA in $SECRET" >&2; exit 1; }
if grep -q '^kind: Secret$' install/*.yaml optional/*.yaml; then echo "install/ or optional/ still contains a Secret" >&2; exit 1; fi
echo "Done."
